// Package config loads the node configuration from YAML plus environment
// overrides. Secret-bearing values should be delivered via environment
// (MCNODE_ENROLL_TOKEN, MCNODE_FRPC_TOKEN); the checked-in example file only
// contains placeholders.
package config

import (
	"errors"
	"fmt"
	"os"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// TLSConfig controls the node's TLS server certificate.
type TLSConfig struct {
	// CertFile/KeyFile point to operator-provided material; when set together
	// they disable autogeneration.
	CertFile string `yaml:"certFile"`
	KeyFile  string `yaml:"keyFile"`
	// AutoGen generates and persists a self-signed certificate under dataDir
	// when no explicit cert/key is configured. Default true.
	AutoGen bool `yaml:"autogen"`
	// Hostname is included in autogenerated cert SANs and used as CN.
	Hostname string `yaml:"hostname"`
}

// PanelConfig describes how to reach the panel for bootstrap.
type PanelConfig struct {
	// URL is the panel base URL, e.g. https://panel.example.com
	URL string `yaml:"url"`
	// TLSPinSha256 is an admin-provided leaf SHA-256 pin for the panel TLS
	// certificate. When set, bootstrap verifies the pin INSTEAD of PKIX.
	// When empty, standard PKIX/hostname verification applies.
	// The pin must be provisioned out-of-band BEFORE bootstrap; it is never
	// learned or updated from panel responses.
	TLSPinSha256 string `yaml:"tlsPinSha256"`
}

// EnrollConfig carries the one-time bootstrap token. Prefer the
// MCNODE_ENROLL_TOKEN environment variable over files.
type EnrollConfig struct {
	Token string `yaml:"token"`
}

// CredentialConfig selects where the issued node identity persists.
type CredentialConfig struct {
	Path string `yaml:"path"`
}

// FRPCConfig configures the embedded frpc control tunnel. The tunnel forwards
// raw TCP end-to-end to the node TLS listener; it never terminates TLS.
type FRPCConfig struct {
	Enabled    bool   `yaml:"enabled"`
	ServerAddr string `yaml:"serverAddr"`
	ServerPort int    `yaml:"serverPort"`
	// Token is the frps auth token. Prefer MCNODE_FRPC_TOKEN env injection.
	// frp tokens are shared per-frps and are only acceptable for isolated
	// local experiments, not as production credentials.
	Token     string `yaml:"token"`
	User      string `yaml:"user"`
	ProxyName string `yaml:"proxyName"`
	// RemotePort is the frps ingress port that reaches the node /control TLS
	// endpoint through the tunnel.
	RemotePort int `yaml:"remotePort"`
	// LocalIP/LocalPort is the node TLS listener the tunnel points at.
	LocalIP   string `yaml:"localIP"`
	LocalPort int    `yaml:"localPort"`
}

// DataConfig describes instance data placement. Root is the path the node
// itself uses; HostRoot is the same directory as seen by the Docker engine
// (differs when the node itself runs in a container with a volume mount).
type DataConfig struct {
 Root string `yaml:"root"`
 HostRoot string `yaml:"hostRoot"`
}

// TrashConfig 控制实例删除后的回收站：删除实例时数据目录改名进 data/trash/，
// 超过 RetentionDays 天的回收目录被每小时清扫永久删除；0 表示永久保留（不清扫）。
type TrashConfig struct {
 RetentionDays int `yaml:"retentionDays"`
}

// FTPConfig 控制临时 SFTP 服务的端口分配：ftp.open 未显式指定端口时，
// 按 basePort + (实例ID哈希 % span) 在 [basePort, basePort+span) 内取值。
// 部署需将该段端口发布到宿主（容器内节点监听 basePort 段）。
// FileRootConfig 命名的节点文件根：节点文件管理/FTP 可访问的目录白名单。
type FileRootConfig struct {
 Name string `yaml:"name"`
 Path string `yaml:"path"`
}

// SecurityConfig 节点机级危险能力开关（终端=节点机 shell）。
type SecurityConfig struct {
 TerminalEnabled bool `yaml:"terminalEnabled"`
}

type FTPConfig struct {
 BasePort int `yaml:"basePort"`
 Span     int `yaml:"span"`
}

// Config is the full node configuration.
type Config struct {
 DataDir    string           `yaml:"dataDir"`
 Data       DataConfig       `yaml:"data"`
 Trash      TrashConfig      `yaml:"trash"`
 FTP        FTPConfig        `yaml:"ftp"`
 FileRoots  []FileRootConfig `yaml:"fileRoots"`
 Security   SecurityConfig   `yaml:"security"`
 Listen     string           `yaml:"listen"`
 LogLevel   string           `yaml:"logLevel"`
 TLS        TLSConfig        `yaml:"tls"`
 Panel      PanelConfig      `yaml:"panel"`
 Enroll     EnrollConfig     `yaml:"enroll"`
 Credential CredentialConfig `yaml:"credential"`
 FRPC       FRPCConfig       `yaml:"frpc"`
}

// Defaults returns the built-in defaults.
func Defaults() *Config {
	return &Config{
		DataDir:  "./data",
		Listen:   "127.0.0.1:7443",
		LogLevel: "info",
		TLS:      TLSConfig{AutoGen: true},
		FRPC:     FRPCConfig{LocalIP: "127.0.0.1"},
		FTP:      FTPConfig{BasePort: 2121, Span: 16},
		Trash:    TrashConfig{RetentionDays: 14},
		FileRoots: []FileRootConfig{{Name: "data", Path: ""}},
		Security:  SecurityConfig{TerminalEnabled: true},
	}
}

// Load reads path (optional), applies defaults, then environment overrides,
// then validates. Missing file is not an error when path == "" (defaults only).
func Load(path string) (*Config, error) {
	cfg := Defaults()
	if path != "" {
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("read config %s: %w", path, err)
		}
		if err := yaml.Unmarshal(data, cfg); err != nil {
			return nil, fmt.Errorf("parse config %s: %w", path, err)
		}
	}
	applyEnv(cfg)
	normalizeFileRoots(cfg)
	if err := cfg.Validate(); err != nil {
		return nil, err
	}
	return cfg, nil
}

// normalizeFileRoots resolves file roots declared without an explicit path to
// the node data directory. The default fileRoots entry is {name: data, path: ""}
// precisely to expose the data dir; without this fallback every node.file.*
// request fails with "节点未配置文件根" on stock configs.
func normalizeFileRoots(cfg *Config) {
	for i := range cfg.FileRoots {
		if strings.TrimSpace(cfg.FileRoots[i].Path) == "" {
			if strings.TrimSpace(cfg.FileRoots[i].Name) == "" {
				cfg.FileRoots[i].Name = "data"
			}
			cfg.FileRoots[i].Path = cfg.DataDir
		}
	}
}

func applyEnv(cfg *Config) {
 if v := os.Getenv("MCNODE_DATA_DIR"); v != "" {
  cfg.DataDir = v
 }
 if v := os.Getenv("MCNODE_DATA_HOST_ROOT"); v != "" {
  cfg.Data.HostRoot = v
 }
 if v := os.Getenv("MCNODE_FILE_ROOT"); v != "" && len(cfg.FileRoots) > 0 {
  cfg.FileRoots[0].Path = v
 }
 if v := os.Getenv("MCNODE_FTP_BASE_PORT"); v != "" {
  if n, err := strconv.Atoi(v); err == nil {
   cfg.FTP.BasePort = n
  }
 }
 if v := os.Getenv("MCNODE_TRASH_RETENTION_DAYS"); v != "" {
  if n, err := strconv.Atoi(v); err == nil {
   cfg.Trash.RetentionDays = n
  }
 }
 if v := os.Getenv("MCNODE_LISTEN"); v != "" {
		cfg.Listen = v
	}
	if v := os.Getenv("MCNODE_LOG_LEVEL"); v != "" {
		cfg.LogLevel = v
	}
	if v := os.Getenv("MCNODE_TLS_HOSTNAME"); v != "" {
		cfg.TLS.Hostname = v
	}
	if v := os.Getenv("MCNODE_PANEL_URL"); v != "" {
		cfg.Panel.URL = v
	}
	if v := os.Getenv("MCNODE_PANEL_TLS_PIN_SHA256"); v != "" {
		cfg.Panel.TLSPinSha256 = v
	}
	if v := os.Getenv("MCNODE_ENROLL_TOKEN"); v != "" {
		cfg.Enroll.Token = v
	}
	if v := os.Getenv("MCNODE_FRPC_TOKEN"); v != "" {
		cfg.FRPC.Token = v
	}
}

// Validate checks structural invariants that do not depend on the command.
func (c *Config) Validate() error {
	if strings.TrimSpace(c.DataDir) == "" {
		return errors.New("dataDir must not be empty")
	}
	if strings.TrimSpace(c.Listen) == "" {
		return errors.New("listen must not be empty")
	}
	if err := validateListenAddr(c.Listen); err != nil {
		return fmt.Errorf("listen: %w", err)
	}
	if !c.TLS.AutoGen && c.TLS.CertFile == "" && c.TLS.KeyFile == "" {
		return errors.New("tls.autogen=false requires tls.certFile and tls.keyFile")
	}
	if (c.TLS.CertFile == "") != (c.TLS.KeyFile == "") {
		return errors.New("tls.certFile and tls.keyFile must be set together")
	}
	if v := c.Panel.TLSPinSha256; v != "" && len(v) != 64 {
		return errors.New("panel.tlsPinSha256 must be 64 hex chars (SHA-256)")
	}
	return nil
}

// ValidateEnroll checks the fields required by the enroll command.
func (c *Config) ValidateEnroll() error {
	if strings.TrimSpace(c.Panel.URL) == "" {
		return errors.New("panel.url is required for bootstrap")
	}
	if strings.TrimSpace(c.Enroll.Token) == "" {
		return errors.New("enroll token is required (config enroll.token or MCNODE_ENROLL_TOKEN)")
	}
	return nil
}

func validateListenAddr(addr string) error {
	idx := strings.LastIndex(addr, ":")
	if idx < 0 {
		return errors.New("expected host:port")
	}
	port := addr[idx+1:]
	if port == "" {
		return errors.New("port missing")
	}
	for _, r := range port {
		if r < '0' || r > '9' {
			return errors.New("port must be numeric (use :0 for a random port only in tests)")
		}
	}
	return nil
}
