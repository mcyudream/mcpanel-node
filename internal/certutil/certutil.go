// Package certutil manages the node TLS certificate lifecycle:
// load operator-provided cert/key, or generate and persist a self-signed
// certificate on first boot, and compute the leaf SHA-256 fingerprint that
// admins pin on the panel side.
package certutil

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/hex"
	"encoding/pem"
	"errors"
	"fmt"
	"math/big"
	"net"
	"os"
	"path/filepath"
	"time"
)

// Manager resolves the node TLS certificate.
type Manager struct {
	// CertFile and KeyFile point to operator-provided material. When both are
	// set they take precedence over autogeneration.
	CertFile string
	KeyFile  string
	// DataDir is where the autogenerated certificate persists.
	DataDir string
	// Hostname is included in the autogenerated cert SANs.
	Hostname string
}

const (
	autoCertFile = "node-cert.pem"
	autoKeyFile  = "node-key.pem"
	certValidity = 10 * 365 * 24 * time.Hour
)

// Ensure returns the TLS certificate and the parsed leaf. Autogenerated
// material is created once and reused from disk on subsequent boots.
func (m *Manager) Ensure() (tls.Certificate, *x509.Certificate, error) {
	if m.CertFile != "" || m.KeyFile != "" {
		if m.CertFile == "" || m.KeyFile == "" {
			return tls.Certificate{}, nil, errors.New("tls.certFile and tls.keyFile must be set together")
		}
		return loadFiles(m.CertFile, m.KeyFile)
	}
	if m.DataDir == "" {
		return tls.Certificate{}, nil, errors.New("dataDir is required for tls autogeneration")
	}
	certPath := filepath.Join(m.DataDir, autoCertFile)
	keyPath := filepath.Join(m.DataDir, autoKeyFile)
	if certExists(certPath, keyPath) {
		return loadFiles(certPath, keyPath)
	}
	if err := os.MkdirAll(m.DataDir, 0o700); err != nil {
		return tls.Certificate{}, nil, fmt.Errorf("create data dir: %w", err)
	}
	if err := generate(certPath, keyPath, m.Hostname); err != nil {
		return tls.Certificate{}, nil, err
	}
	return loadFiles(certPath, keyPath)
}

// FingerprintPath computes the leaf SHA-256 fingerprint of the resolved
// certificate without touching TLS state. Used by the fingerprint CLI command.
func (m *Manager) FingerprintPath() (string, *x509.Certificate, error) {
	_, leaf, err := m.Ensure()
	if err != nil {
		return "", nil, err
	}
	return FingerprintHex(leaf.Raw), leaf, nil
}

// FingerprintHex returns the lowercase hex SHA-256 of a DER-encoded leaf cert.
func FingerprintHex(der []byte) string {
	sum := sha256.Sum256(der)
	return hex.EncodeToString(sum[:])
}

func certExists(certPath, keyPath string) bool {
	if _, err := os.Stat(certPath); err != nil {
		return false
	}
	if _, err := os.Stat(keyPath); err != nil {
		return false
	}
	return true
}

func loadFiles(certPath, keyPath string) (tls.Certificate, *x509.Certificate, error) {
	cert, err := tls.LoadX509KeyPair(certPath, keyPath)
	if err != nil {
		return tls.Certificate{}, nil, fmt.Errorf("load tls keypair: %w", err)
	}
	if len(cert.Certificate) == 0 {
		return tls.Certificate{}, nil, errors.New("tls keypair has no certificate chain")
	}
	leaf, err := x509.ParseCertificate(cert.Certificate[0])
	if err != nil {
		return tls.Certificate{}, nil, fmt.Errorf("parse leaf certificate: %w", err)
	}
	return cert, leaf, nil
}

func generate(certPath, keyPath, hostname string) error {
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return fmt.Errorf("generate key: %w", err)
	}

	cn := hostname
	if cn == "" {
		cn = "mcpanel-node"
	}
	dnsNames := []string{cn, "localhost"}
	ips := []net.IP{net.ParseIP("127.0.0.1"), net.ParseIP("::1")}

	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 128))
	if err != nil {
		return fmt.Errorf("generate serial: %w", err)
	}
	tmpl := x509.Certificate{
		SerialNumber:          serial,
		Subject:               pkix.Name{CommonName: cn, Organization: []string{"mcpanel-node"}},
		NotBefore:             time.Now().Add(-1 * time.Hour),
		NotAfter:              time.Now().Add(certValidity),
		KeyUsage:              x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
		DNSNames:              dnsNames,
		IPAddresses:           ips,
	}
	der, err := x509.CreateCertificate(rand.Reader, &tmpl, &tmpl, &key.PublicKey, key)
	if err != nil {
		return fmt.Errorf("create certificate: %w", err)
	}

	keyDER, err := x509.MarshalECPrivateKey(key)
	if err != nil {
		return fmt.Errorf("marshal key: %w", err)
	}
	keyPEM := pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: keyDER})
	certPEM := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})

	if err := writeFileAtomic(keyPath, keyPEM, 0o600); err != nil {
		return fmt.Errorf("write key: %w", err)
	}
	if err := writeFileAtomic(certPath, certPEM, 0o644); err != nil {
		return fmt.Errorf("write cert: %w", err)
	}
	return nil
}

// writeFileAtomic writes via temp file + fsync + rename; perm applies to the
// final file (enforced again after rename; chmod first for POSIX mode races).
func writeFileAtomic(path string, data []byte, perm os.FileMode) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer func() {
		_ = os.Remove(tmpName)
	}()
	if err := tmp.Chmod(perm); err != nil {
		tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmpName, path); err != nil {
		return err
	}
	// Belt and braces: enforce final mode even where Chmod on the temp file
	// was a no-op (e.g. Windows semantics inside a mounted volume).
	if err := os.Chmod(path, perm); err != nil {
		return err
	}
	return nil
}
